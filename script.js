function applyTranslations(lang) {
    const dict = translations[lang];
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const keys = key.split(".");
        let val = dict;
        for (let k of keys) {
            if (val && val[k]) val = val[k];
            else val = null;
        }
        if (val) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = val;
            } else {
                el.innerHTML = val;
            }
        }
    });
}

/* ==========================================
   TYPING ANIMATION
   ========================================== */
function initTypingEffect() {
    const typingSpan = document.getElementById("typing-text");
    if (!typingSpan) return;

    let textIdx = 0;
    let charIdx = 0;
    let isDeleting = false;
    let delay = 150;

    function typeLoop() {
        const texts = translations[currentLang].hero.typingTexts;
        const currentString = texts[textIdx % texts.length];

        if (!isDeleting) {
            typingSpan.textContent = currentString.substring(0, charIdx + 1);
            charIdx++;
            if (charIdx === currentString.length) {
                isDeleting = true;
                delay = 2000;
            } else {
                delay = 150;
            }
        } else {
            typingSpan.textContent = currentString.substring(0, charIdx - 1);
            charIdx--;
            if (charIdx === 0) {
                isDeleting = false;
                textIdx++;
                delay = 500;
            } else {
                delay = 100;
            }
        }
        setTimeout(typeLoop, delay);
    }
    typeLoop();
}

/* ==========================================
   COUNTER ANIMATION
   ========================================== */
function initCounters() {
    const counters = document.querySelectorAll(".counter");
    let animated = false;

    window.addEventListener("scroll", () => {
        const scrollPos = window.scrollY + window.innerHeight;
        const statsSection = document.querySelector(".stats-section");
        if (!statsSection) return;

        if (!animated && scrollPos > statsSection.offsetTop) {
            counters.forEach(counter => {
                const target = +counter.getAttribute("data-target");
                let count = 0;
                const speed = target / 40;

                const updateCount = () => {
                    count += speed;
                    if (count < target) {
                        counter.textContent = Math.ceil(count);
                        setTimeout(updateCount, 30);
                    } else {
                        counter.textContent = target;
                    }
                };
                updateCount();
            });
            animated = true;
        }
    });
}

