/* ==========================================
   EVENT LISTENERS & INTERACTIVE BEHAVIORS
   ========================================== */
function initEventListeners() {
    // Mobile Menu Toggle
    const mobileBtn = document.getElementById("mobile-menu-btn");
    const mobileMenu = document.getElementById("mobile-menu");

    mobileBtn?.addEventListener("click", () => {
        mobileMenu.classList.toggle("open");
    });

    mobileMenu?.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", () => {
            mobileMenu.classList.remove("open");
        });
    });

    // Gallery Filters
    document.querySelectorAll(".filter-btn").forEach(btn => {
        btn.addEventListener("click", (e) => {
            document.querySelectorAll(".filter-btn").forEach(b => b.classList.remove("active"));
            e.target.classList.add("active");
            renderGallery(e.target.getAttribute("data-filter"));
        });
    });

    // Cursor Glow & Scroll Progress
    window.addEventListener("mousemove", (e) => {
        document.documentElement.style.setProperty("--cursor-x", `${e.clientX}px`);
        document.documentElement.style.setProperty("--cursor-y", `${e.clientY}px`);
    });

    window.addEventListener("scroll", () => {
        const totalScroll = document.documentElement.scrollHeight - document.documentElement.clientHeight;
        const currentScroll = window.scrollY;
        const progress = (currentScroll / totalScroll) * 100;
        const progressBar = document.getElementById("scroll-progress");
        if (progressBar) progressBar.style.width = `${progress}%`;
    });

    // Ripple Button Effect
    document.querySelectorAll(".ripple-btn").forEach(btn => {
        btn.addEventListener("click", function(e) {
            const rect = this.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const y = e.clientY - rect.top;

            const ripple = document.createElement("span");
            ripple.classList.add("ripple");
            ripple.style.left = `${x}px`;
            ripple.style.top = `${y}px`;
            this.appendChild(ripple);

            setTimeout(() => ripple.remove(), 600);
        });
    });

    // Guestbook Form Submission
    const gbForm = document.getElementById("guestbook-form");
    gbForm?.addEventListener("submit", (e) => {
        e.preventDefault();
        const name = document.getElementById("gb-name").value.trim();
        const message = document.getElementById("gb-message").value.trim();

        if (!name || !message) return;

        const saved = localStorage.getItem("portfolio_guestbook");
        const items = saved ? JSON.parse(saved) : initialGuestbook;

        const newItem = {
            id: Date.now(),
            name,
            message,
            date: new Date().toISOString().split("T")[0]
        };

        items.unshift(newItem);
        localStorage.setItem("portfolio_guestbook", JSON.stringify(items));

        document.getElementById("gb-name").value = "";
        document.getElementById("gb-message").value = "";

        const alertBox = document.getElementById("guestbook-alert");
        alertBox.classList.remove("hidden");
        setTimeout(() => alertBox.classList.add("hidden"), 4000);

        renderGuestbook();
    });

    // Contact Form Submission
    const cForm = document.getElementById("contact-form");
    cForm?.addEventListener("submit", (e) => {
        e.preventDefault();
        document.getElementById("c-name").value = "";
        document.getElementById("c-email").value = "";
        document.getElementById("c-subject").value = "";
        document.getElementById("c-message").value = "";

        const alertBox = document.getElementById("contact-alert");
        alertBox.classList.remove("hidden");
        setTimeout(() => alertBox.classList.add("hidden"), 5000);
    });
}
